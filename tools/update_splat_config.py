#!/usr/bin/env python3
"""Generate per-function Splat subsegments from the linked debug ELF.

The MWCC debug stream supplies source-unit ownership for a large subset of
functions, while .symtab supplies an address and label for every emitted code
symbol.  Contiguous source-owned function ranges become Splat asm segments,
so the generated assembly follows the recovered source-file layout without
creating one expensive disassembler instance per function.
"""

from __future__ import annotations

import re
from pathlib import Path

from extract_debug import DebugParser, STT_FUNC, parse_symtab, read_elf_sections


ROOT = Path(__file__).resolve().parent.parent
ELF_PATH = ROOT / "SLKA_250.78"
CONFIG_PATH = ROOT / "config" / "rayman3.yaml"
SOURCE_SYMBOLS_PATH = ROOT / "config" / "symbols.txt"
SPLAT_SYMBOLS_PATH = ROOT / "config" / "splat_symbols.txt"


def safe_component(value: str) -> str:
    value = re.sub(r"[^A-Za-z0-9_.-]+", "_", value).strip("._")
    return value or "unnamed"


def source_dir(path: str, address: int) -> str:
    """Turn a debug Windows source path into a safe asm-relative directory."""
    path = path.replace("\\", "/")
    marker = "Rayman3/"
    if marker in path:
        path = path[path.index(marker):]
    else:
        path = "unknown"
    path = path.rsplit(".", 1)[0]
    components = [safe_component(component) for component in path.split("/") if component]
    return "/".join(components) or f"unknown/{address:08X}"


def symbol_rank(name: str) -> tuple[int, int, str]:
    """Prefer useful labels over linker/compiler aliases at one address."""
    generated = name in {"ENTRYPOINT", "__gnu_compiled_c", "gcc2_compiled."}
    return (int(generated), len(name), name)


def write_splat_symbols(function_addresses: set[int], debug_names: dict[int, str]) -> int:
    """Produce Splat's alias-free view without changing the full symbol dump."""
    candidates: dict[int, list[str]] = {}
    line_pattern = re.compile(r"^\s*([^=\s]+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*;")
    for line in SOURCE_SYMBOLS_PATH.read_text().splitlines():
        match = line_pattern.match(line)
        if match:
            candidates.setdefault(int(match.group(2), 0), []).append(match.group(1))

    used_names: set[str] = set()
    lines = ["// Generated by tools/update_splat_config.py; do not edit."]
    for address in sorted(candidates):
        names = candidates[address]
        debug_name = debug_names.get(address)
        if debug_name in names:
            names = [debug_name, *[name for name in names if name != debug_name]]
        else:
            names = sorted(names, key=symbol_rank)
        name = next((candidate for candidate in names if candidate not in used_names), None)
        if name is None:
            continue
        used_names.add(name)
        # Splat validates every symbol's potential output filename even when
        # this project supplies explicit per-function segment filenames.
        # MWCC C++ names can contain '<', '>', and ':'; pin a safe filename
        # for all labels.
        attrs = [f"filename:sym_{address:08X}"]
        if address in function_addresses:
            attrs.insert(0, "type:func")
        suffix = " // " + " ".join(attrs)
        lines.append(f"{name} = 0x{address:08X};{suffix}")
    SPLAT_SYMBOLS_PATH.write_text("\n".join(lines) + "\n")
    return len(lines) - 1


def main() -> None:
    data = ELF_PATH.read_bytes()
    sections = read_elf_sections(data)
    main_section = sections["main"]
    debug_data = sections[".debug"]["data"]
    symbols = parse_symtab(sections[".symtab"]["data"], sections[".strtab"]["data"])

    function_symbols = [
        symbol for symbol in symbols
        if symbol.type_ == STT_FUNC
        and main_section["addr"] <= symbol.value < main_section["addr"] + main_section["size"]
    ]
    function_addresses = {symbol.value for symbol in function_symbols}

    debug_sources = {}
    debug_names = {}
    # Prefer debug-derived source ownership where it is available.  The
    # per-address mapping deliberately keeps the first record: later aliases
    # in .symtab name the same machine-code range.
    debug_functions = DebugParser(
        debug_data, function_addresses=function_addresses
    ).parse()
    for file_info in debug_functions:
        for function in file_info.functions:
            debug_sources.setdefault(function.addr, file_info.path)
            debug_names.setdefault(function.addr, function.name)

    names = {}
    for symbol in function_symbols:
        if symbol.name:
            names.setdefault(symbol.value, symbol.name)

    # Start a new range only when the source ownership changes.  536 ranges
    # are tractable for Splat; one segment per 7,832 functions is not.  A
    # source may recur after inlined/template/header code; suffix its later
    # fragments rather than overwriting an earlier assembly file.
    source_runs = []
    current_source = None
    for address in sorted(names):
        source = source_dir(debug_sources.get(address, "unknown"), address)
        if source != current_source:
            rom_start = main_section["offset"] + address - main_section["addr"]
            source_runs.append((rom_start, source))
            current_source = source
    if not source_runs or source_runs[0][0] != main_section["offset"]:
        source_runs.insert(0, (main_section["offset"], "unknown"))

    source_parts: dict[str, int] = {}
    lines = ["    subsegments:"]
    for rom_start, source in source_runs:
        source_parts[source] = source_parts.get(source, 0) + 1
        part = source_parts[source]
        output_name = source if part == 1 else f"{source}__part{part}"
        lines.append(f"      - [0x{rom_start:X}, asm, {output_name}]")
    generated = "\n".join(lines)

    config = CONFIG_PATH.read_text()
    old = re.compile(
        r"    sub(?:sections|segments):\n.*?(?=\n  - \[0x26A900\])", re.DOTALL
    )
    if not old.search(config):
        raise RuntimeError("Could not locate main.subsegments in config/rayman3.yaml")
    CONFIG_PATH.write_text(old.sub(generated, config, count=1))
    config = CONFIG_PATH.read_text()
    config = config.replace(
        "    - config/symbols.txt", "    - config/splat_symbols.txt"
    )
    CONFIG_PATH.write_text(config)
    symbol_count = (
        len(SPLAT_SYMBOLS_PATH.read_text().splitlines()) - 1
        if SPLAT_SYMBOLS_PATH.exists()
        else write_splat_symbols(function_addresses, debug_names)
    )
    print(
        f"Wrote {len(source_runs)} source-owned asm ranges ({len(function_addresses)} "
        f"function addresses; {len(debug_sources)} with debug source ownership) and "
        f"{symbol_count} alias-free symbols for Splat"
    )


if __name__ == "__main__":
    main()
